#!/usr/bin/env bash
# Shared settings and helpers for tv-mode.sh / desktop-mode.sh.
# Settings live in ~/.config/caelestia/tvmode.json (edited from the bar popout);
# anything missing falls back to the defaults below.

CONF=${XDG_CONFIG_HOME:-$HOME/.config}/caelestia/tvmode.json
CACHE=${XDG_CACHE_HOME:-$HOME/.cache}/tv-mode
mkdir -p "$CACHE"

conf() { # conf <jq path> <default>
  local v=""
  [[ -f $CONF ]] && v=$(jq -r "$1 | select(. != null) | if type == \"array\" then join(\" \") else tostring end" "$CONF" 2>/dev/null)
  printf '%s' "${v:-$2}"
}

read -r -a DESKTOP_MONITORS <<<"$(conf .desktopMonitors 'DP-1 DP-3')"
TV=$(conf .tv HDMI-A-1)
TV_MODE=$(conf .tvMode 3840x2160@60)
TV_SCALE=$(conf .tvScale 1)
TV_AUDIO_MATCH=$(conf .tvAudioMatch SAMSUNG)    # matched against the HDMI port's device name (from the TV's EDID)
CLOSE_WINDOWS=$(conf .closeWindows true)
KEEP_CLASS_REGEX=$(conf .keepClassRegex 'caelestia|quickshell|steam')
TV_IN_DESKTOP=$(conf .tvInDesktop false)        # keep the TV on as an extra screen in desktop mode
STEAM_CMD=$(conf .steamCommand 'steam -gamepadui')
KEEP_AWAKE=$(conf .keepAwake true)               # no lock screen, screen blanking or suspend while in TV mode

log() { printf '[tv-mode] %s\n' "$*" >&2; }
notify() { command -v notify-send >/dev/null && notify-send -a "TV Mode" -i video-display "$@" || true; }
state() { printf '%s\n' "$1" >"$CACHE/state"; }

# Monitor layout per mode goes into an override file that the Hyprland config loads after its
# own monitor rules, then `hyprctl reload` applies it. (A runtime `hl.monitor` eval doesn't
# override a rule that's already in the config.) Both formats are written:
#   Lua config (hyprland.lua):   pcall(dofile, os.getenv("HOME") .. "/.config/caelestia/tvmode-monitors.lua")
#   hyprland.conf:               source = ~/.config/caelestia/tvmode-monitors.conf
LAYOUT_LUA=${XDG_CONFIG_HOME:-$HOME/.config}/caelestia/tvmode-monitors.lua
LAYOUT_CONF=${XDG_CONFIG_HOME:-$HOME/.config}/caelestia/tvmode-monitors.conf

apply_layout() { # apply_layout tv|desktop
  local lua="-- Generated by caelestia-tvmode ($1 mode). Don't edit, it's rewritten on every switch."
  local conf="# Generated by caelestia-tvmode ($1 mode). Don't edit, it's rewritten on every switch."
  if [[ $1 == tv ]]; then
    lua+=$'\n'"hl.monitor({ output = \"$TV\", mode = \"$TV_MODE\", position = \"0x0\", scale = $TV_SCALE })"
    conf+=$'\n'"monitor = $TV,$TV_MODE,0x0,$TV_SCALE"
    for m in "${DESKTOP_MONITORS[@]}"; do
      lua+=$'\n'"hl.monitor({ output = \"$m\", disabled = true })"
      conf+=$'\n'"monitor = $m,disable"
    done
  elif [[ $TV_IN_DESKTOP != true ]]; then
    lua+=$'\n'"hl.monitor({ output = \"$TV\", disabled = true })"
    conf+=$'\n'"monitor = $TV,disable"
  fi
  printf '%s\n' "$lua" >"$LAYOUT_LUA"
  printf '%s\n' "$conf" >"$LAYOUT_CONF"
  hyprctl reload >/dev/null
}

layout_hooked() { # is the override file loaded by the Hyprland config?
  grep -rqs 'tvmode-monitors' "${XDG_CONFIG_HOME:-$HOME/.config}/hypr" "${XDG_CONFIG_HOME:-$HOME/.config}/caelestia/hypr-user.lua" "${XDG_CONFIG_HOME:-$HOME/.config}/caelestia/hypr-user.conf"
}

# Keep awake: the shell's own idle inhibitor (stops its lock screen and DPMS timeouts) plus a
# logind inhibitor (stops suspend from anything else). The inhibitor's previous state is saved, so
# a keep-awake you turned on yourself stays on after desktop mode.
shell_ipc() { # shell_ipc <target> <function>
  if command -v caelestia >/dev/null; then caelestia shell "$@" 2>/dev/null
  else qs ipc -c caelestia call "$@" 2>/dev/null; fi
}

awake_on() {
  [[ -f $CACHE/inhibitor-was.txt ]] || shell_ipc idleInhibitor isEnabled >"$CACHE/inhibitor-was.txt"
  shell_ipc idleInhibitor enable >/dev/null
  if [[ ! -s $CACHE/inhibit.pid ]] || ! kill -0 "$(cat "$CACHE/inhibit.pid")" 2>/dev/null; then
    setsid -f sh -c 'echo $$ >"$1"; exec systemd-inhibit --what=sleep:idle --who="TV Mode" --why="TV mode is on" --mode=block sleep infinity' _ "$CACHE/inhibit.pid" >/dev/null 2>&1
  fi
}

awake_off() {
  if [[ -f $CACHE/inhibitor-was.txt ]]; then
    [[ $(cat "$CACHE/inhibitor-was.txt") == true ]] || shell_ipc idleInhibitor disable >/dev/null
    rm -f "$CACHE/inhibitor-was.txt"
  fi
  if [[ -s $CACHE/inhibit.pid ]]; then
    pkill -P "$(cat "$CACHE/inhibit.pid")" 2>/dev/null; kill "$(cat "$CACHE/inhibit.pid")" 2>/dev/null
    rm -f "$CACHE/inhibit.pid"
  fi
}

tv_active() { # TV enabled with a real mode
  hyprctl monitors -j | jq -e --arg tv "$TV" '.[] | select(.name == $tv and .disabled == false and .width > 0)' >/dev/null
}

move_streams() { # move every playing stream to sink $1
  pactl list short sink-inputs | awk '{print $1}' | while read -r id; do
    pactl move-sink-input "$id" "$1" 2>/dev/null || true
  done
}

wait_sink() { # wait_sink <card> <profile> → prints sink name
  local profile=${2#output:} s
  for _ in $(seq 1 20); do
    s=$(pactl -f json list sinks | jq -r --arg c "$1" --arg p "$profile" \
      'first(.[] | select(.properties["device.name"] == $c and .properties["device.profile.name"] == $p) | .name) // empty')
    [[ -n $s ]] && { printf '%s' "$s"; return 0; }
    sleep 0.5
  done
  return 1
}
